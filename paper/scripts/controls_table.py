"""Summary table of the retrained controls (formal_controls_kvasir_v1), from data/review/controls_results.json."""
import json
import numpy as np
R = json.load(open('data/review/controls_results.json'))
OOD = ['ColonDB', 'ClinicDB', 'CVC300', 'BKAI']
def ood(arm, cfg):
    a = R['arms'][arm].get(cfg)
    if not a:
        return None
    per = [np.mean([a[t]['DSC'][i] for t in OOD]) for i in range(3)]
    return np.mean(per), np.std(per, ddof=1), np.mean(a['Kvasir']['DSC'])
rows = [('orig_fixed', 'Original recipe (one view per step, public Dice)'), ('orig_fixed_dice', '+ corrected Dice'),
        ('flip', '+ ordinary random flip'), ('baseline', 'Paired reflection (our baseline)'),
        ('detail', 'Detail branch, real $448$ image'), ('detail_up224', 'Detail branch, upsampled $224$ image'),
        ('detail_scale', 'Detail branch + scale augmentation')]
L = ['% Generated by scripts/controls_table.py from data/review/controls_results.json.',
     '\\begin{tabularx}{\\linewidth}{@{}XCCC@{}}', '\\toprule',
     'Training configuration (fixed sentence) & Kvasir-SEG & OOD mean & OOD mean with SCZ \\\\', '\\midrule']
for key, label in rows:
    s = ood(key, 'single'); z = ood(key, 't15')
    L.append(f'{label} & {s[2]:.2f} & {s[0]:.2f}\\sd{{{s[1]:.2f}}} & ' + (f'{z[0]:.2f}\\sd{{{z[1]:.2f}}}' if z else '--') + ' \\\\')
L += ['\\midrule', '\\multicolumn{4}{@{}l}{\\emph{Paired OOD differences (pp; per seed)}} \\\\']
C = R['contrasts']
for key, label in [('dice_fix', 'Dice correction'), ('random_flip', 'Ordinary random flip'), ('paired_vs_flip', 'Paired reflection instead of ordinary flip'),
                   ('recipe_total', 'Recipe in total'), ('detail_branch', 'Detail branch'), ('true_448_vs_upsampled', 'Real minus upsampled detail input'),
                   ('scale_aug', 'Scale augmentation'), ('two_pass_on_detail', 'SCZ on the detail-branch model'),
                   ('two_pass_on_detail_scale', 'SCZ after scale augmentation'), ('two_pass_on_baseline', 'SCZ on the baseline')]:
    c = C[key]
    L.append(f"{label} & \\multicolumn{{3}}{{l}}{{${c['macro_ood_pp']:+.2f}$ \\quad ({', '.join(f'{v:+.2f}' for v in c['macro_ood_per_seed_pp'])})}} \\\\")
L += ['\\bottomrule', '\\end{tabularx}',
      '\\tabnote{DSC (\\%), mean\\,$\\pm$\\,SD over seeds 666--668; all models trained on one RTX~5060~Ti with the fixed sentence. '
      'The single-view configurations use half the forward and backward passes per optimisation step of the paired ones. '
      'The detail-branch rows in \\cref{tab:main} come from other hardware and five seeds.}']
open('tables/tab_controls.tex', 'w').write('\n'.join(L) + '\n')
