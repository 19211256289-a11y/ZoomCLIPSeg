"""Mean IoU of the four fixed-sentence polyp models (five seeds), from the per-image DSC records.
For a binary prediction IoU = DSC / (2 - DSC) per image; means are over images, then over seeds."""
import json
S = ['Kvasir', 'ColonDB', 'ClinicDB', 'CVC300', 'BKAI', 'OOD']
d = json.load(open('data/review/iou_summary.json'))
rows = [('Baseline', 'Baseline'), ('Baseline + SCZ', 'Baseline + SCZ'), ('+ Detail branch', 'Detail branch, single pass'), ('ZoomCLIPSeg', '\\method{} (ours)')]
L = ['% Generated by scripts/iou_table.py from data/review/iou_summary.json.', '\\begin{tabularx}{\\linewidth}{@{}lCCCCCC@{}}', '\\toprule',
     'Model & Kvasir-SEG & ColonDB & ClinicDB & CVC-300 & BKAI & OOD mean \\\\', '\\midrule']
for key, label in rows:
    v = d[key]['IoU']
    L.append(('\\rowcolor{ours}' if key == 'ZoomCLIPSeg' else '')+label+' & '+' & '.join(f"{v[t][0]:.2f}\\sd{{{v[t][1]:.2f}}}" for t in S)+' \\\\')
L += ['\\bottomrule', '\\end{tabularx}',
      '\\tabnote{Mean intersection over union (\\%), mean\\,$\\pm$\\,SD over five training seeds (666--670); same predictions as \\cref{tab:main}.}']
open('tables/tab_iou.tex', 'w').write('\n'.join(L)+'\n')
