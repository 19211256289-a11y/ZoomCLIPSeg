def cell(values, bold=False):
    """mean with a small +/- SD; \\sd is defined in main.tex."""
    mean = f'{np.mean(values):.2f}'
    return (f'\\textbf{{{mean}}}' if bold else mean)+f'\\sd{{{np.std(values, ddof=1):.2f}}}'


def sgn(v, digits=2):
    """Signed number with a typographic minus."""
    return f'${v:+.{digits}f}$'


def interval(lo, hi):
    return f'$[{lo:+.2f},\\,{hi:+.2f}]$'


def seedlist(values, digits=2):
    return ', '.join(sgn(v, digits) for v in values)


def write(name, lines, notes=None):
    """Tables are tabularx at the full line width; C is a centred X column (main.tex). Notes go below the table."""
    body = '\n'.join(lines) if isinstance(lines, list) else lines
    if notes:
        body += '\n\\tabnote{'+notes+'}'
    open(f'tables/{name}.tex', 'w', encoding='utf-8').write('% Generated by scripts/make_tables.py; do not edit by hand.\n'+body+'\n')
    print('tables/'+name+'.tex')


